create table employee(
id char(4) primary key,
first_name varchar(10),
last_name varchar(10),
phone char(10),
email varchar(40),
TheRole varchar(10),
Id_number char(9),
hire_date  date,
salary decimal(10,2),
working_hours  int
);


create table UserAccount(
id char(4) primary key,
employee_id char(4),
 foreign key (employee_id) references employee(id),
 username varchar(10),
 password char(10));
 
 create  table categorie(
 id char(4)primary key,
 c_name varchar(20)
 );

create table product(
id char(4) primary key,
p_name varchar(20),
brand varchar(10),
gender varchar(5),
categorie_id char(4),
foreign key(categorie_id) references categorie(id),
description varchar(30),
p_type varchar(10)

);
